import 'package:flutter/material.dart';

/// Paleta de colores de la aplicación Sincbo
/// Basada en el color turquesa del icono de la marca
class AppColors {
  // Colores primarios - Turquesa (color del icono/marca de Sincbo)
  static const Color primary = Color(0xFF00A364); // Turquesa - Color principal de la marca
  static const Color primaryLight = Color(0xFFC8E6C9);
  static const Color primaryDark = Color(0xFF388E3C);

  // Colores secundarios - Púrpura (complementario)
  static const Color secondary = Color(0xFF6B4EFF); // Púrpura vibrante
  static const Color secondaryLight = Color(0xFF9B7FFF);
  static const Color secondaryDark = Color(0xFF4A2FD9);

  // Colores de acento - Rosa
  static const Color accent = Color(0xFFFF6B9D); // Rosa vibrante
  static const Color accentLight = Color(0xFFFF9BB8);
  static const Color accentDark = Color(0xFFD94A7B);

  // Colores de estado
  static const Color success = Color(0xFF00C853);
  static const Color warning = Color(0xFFFFC107);
  static const Color error = Color(0xFFFF5252);
  static const Color info = Color(0xFF2196F3);

  // Neutrales
  static const Color backgroundLight = Color(0xFFFAFAFA);
  static const Color backgroundDark = Color(0xFF121212);
  static const Color surface = Color(0xFFFFFFFF);
  static const Color surfaceDark = Color(0xFF1E1E1E);

  // Textos
  static const Color textPrimary = Color(0xFF212121);
  static const Color textSecondary = Color(0xFF757575);
  static const Color textHint = Color(0xFFBDBDBD);
  static const Color textOnPrimary = Color(0xFFFFFFFF);

  // Bordes y divisores
  static const Color divider = Color(0xFFE0E0E0);
  static const Color border = Color(0xFFCCCCCC);

  // Gradientes
  static const LinearGradient primaryGradient = LinearGradient(
    colors: [primary, primaryLight],
    begin: Alignment.topLeft,
    end: Alignment.bottomRight,
  );

  static const LinearGradient secondaryGradient = LinearGradient(
    colors: [secondary, secondaryLight],
    begin: Alignment.topLeft,
    end: Alignment.bottomRight,
  );

  static const LinearGradient accentGradient = LinearGradient(
    colors: [accent, accentLight],
    begin: Alignment.topLeft,
    end: Alignment.bottomRight,
  );

  static const LinearGradient rainbowGradient = LinearGradient(
    colors: [primary, secondary, accent], // Turquesa → Púrpura → Rosa
    begin: Alignment.topLeft,
    end: Alignment.bottomRight,
  );
}

